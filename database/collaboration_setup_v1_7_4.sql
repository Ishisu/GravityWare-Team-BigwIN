-- GravityWare v1.7.4 collaboration workflow
-- Run this in Supabase SQL Editor as project owner.
-- IMPORTANT: Assign reviewer roles manually. Never let users assign themselves reviewer roles.

create table if not exists public.reviewer_access (
    user_id uuid primary key references auth.users(id) on delete cascade,
    role text not null check (role in ('doctor','mission_control')),
    active boolean not null default true,
    created_at timestamptz not null default now()
);
alter table public.reviewer_access enable row level security;

create or replace function public.gravityware_has_role(required_role text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.reviewer_access
    where user_id = auth.uid()
      and active = true
      and role = required_role
  );
$$;
revoke all on function public.gravityware_has_role(text) from public;
grant execute on function public.gravityware_has_role(text) to authenticated;

drop policy if exists "Users can read their own reviewer role" on public.reviewer_access;
create policy "Users can read their own reviewer role"
on public.reviewer_access for select to authenticated
using (user_id = auth.uid());

create table if not exists public.mission_reviews (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    astronaut_name text not null,
    astronaut_code text not null,
    gravity_environment text not null,
    record_date date not null,
    case_summary text not null,
    status text not null default 'Awaiting medical review',
    doctor_assessment text,
    doctor_recommendation text,
    doctor_reviewer_id uuid references auth.users(id),
    mission_decision text,
    mission_action text,
    mission_reviewer_id uuid references auth.users(id),
    created_by uuid not null references auth.users(id),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
alter table public.mission_reviews enable row level security;

drop policy if exists "Astronauts read own mission reviews" on public.mission_reviews;
create policy "Astronauts read own mission reviews"
on public.mission_reviews for select to authenticated
using (user_id = auth.uid());

drop policy if exists "Astronauts create own mission reviews" on public.mission_reviews;
create policy "Astronauts create own mission reviews"
on public.mission_reviews for insert to authenticated
with check (user_id = auth.uid() and created_by = auth.uid());

drop policy if exists "Doctors read all mission reviews" on public.mission_reviews;
create policy "Doctors read all mission reviews"
on public.mission_reviews for select to authenticated
using (public.gravityware_has_role('doctor'));

drop policy if exists "Mission control read all mission reviews" on public.mission_reviews;
create policy "Mission control read all mission reviews"
on public.mission_reviews for select to authenticated
using (public.gravityware_has_role('mission_control'));

drop policy if exists "Doctors update medical review fields" on public.mission_reviews;
create policy "Doctors update medical review fields"
on public.mission_reviews for update to authenticated
using (public.gravityware_has_role('doctor'))
with check (public.gravityware_has_role('doctor'));

drop policy if exists "Mission control update operational fields" on public.mission_reviews;
create policy "Mission control update operational fields"
on public.mission_reviews for update to authenticated
using (public.gravityware_has_role('mission_control'))
with check (public.gravityware_has_role('mission_control'));

grant select, insert, update on public.mission_reviews to authenticated;
grant select on public.reviewer_access to authenticated;

-- Allow authorized reviewers to view astronaut health records for review.
drop policy if exists "Authorized doctors read astronaut health records" on public.health_records;
create policy "Authorized doctors read astronaut health records"
on public.health_records for select to authenticated
using (public.gravityware_has_role('doctor'));

drop policy if exists "Authorized mission control read astronaut health records" on public.health_records;
create policy "Authorized mission control read astronaut health records"
on public.health_records for select to authenticated
using (public.gravityware_has_role('mission_control'));
