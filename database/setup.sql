-- GravityWare v1.3 database setup
-- Run the entire script in Supabase Dashboard > SQL Editor > New query.
-- Uses Supabase Auth + Row Level Security. Never put a service_role key in Streamlit.

create table if not exists public.health_records (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    record_date date not null,
    mission_day integer not null default 1 check (mission_day >= 0),
    astronaut_name text not null,
    astronaut_code text not null,
    gravity_environment text not null,
    heart_rate integer not null check (heart_rate between 30 and 220),
    systolic_bp integer not null check (systolic_bp between 60 and 250),
    diastolic_bp integer not null check (diastolic_bp between 30 and 160),
    spo2 integer not null check (spo2 between 50 and 100),
    temperature_c numeric(4,1) not null check (temperature_c between 30 and 43),
    sleep_hours numeric(4,1) not null check (sleep_hours between 0 and 24),
    stress_level integer not null check (stress_level between 0 and 10),
    fatigue_level integer not null check (fatigue_level between 0 and 10),
    exercise_minutes integer not null default 0 check (exercise_minutes between 0 and 600),
    mood text not null,
    symptoms text[] not null default '{}',
    notes text,
    created_at timestamptz not null default now(),
    constraint one_daily_record_per_astronaut unique (user_id, astronaut_code, record_date)
);

alter table public.health_records enable row level security;

drop policy if exists "Users can read their own health records" on public.health_records;
create policy "Users can read their own health records"
on public.health_records for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own health records" on public.health_records;
create policy "Users can insert their own health records"
on public.health_records for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own health records" on public.health_records;
create policy "Users can update their own health records"
on public.health_records for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own health records" on public.health_records;
create policy "Users can delete their own health records"
on public.health_records for delete
to authenticated
using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.health_records to authenticated;
grant usage, select on sequence public.health_records_id_seq to authenticated;

create index if not exists health_records_user_date_idx
on public.health_records (user_id, record_date desc);
